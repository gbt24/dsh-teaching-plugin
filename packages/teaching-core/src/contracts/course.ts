/**
 * Courses, their AI-proposed structure revisions, concepts and source roles.
 *
 * A course has immutable structure revisions. One revision is the confirmed
 * (active) one students learn against; a proposed draft revision may coexist
 * and only becomes active after explicit student confirmation (or, for ad-hoc
 * questions, a draft with a single concept can be used read-only).
 */
import type {
  ConceptId, CourseId, CourseRevisionId, SourceId,
} from './ids.ts'
import type { SourceAnchor } from './source.ts'

/** Lifecycle of a course. */
export type CourseStatus = 'draft' | 'active' | 'archived'

/** How one source document participates in a course. */
export type SourceRole = 'textbook' | 'lecture' | 'slides' | 'exercise' | 'reference' | 'other'

/** Whether the course revision is proposed or student-confirmed. */
export type RevisionState = 'draft' | 'confirmed' | 'superseded'

/** Difficulty hint used for teaching-form selection, not a gate. */
export type ConceptDifficulty = 'intro' | 'core' | 'advanced'

/** One teachable concept inside a course revision. */
export interface Concept {
  readonly id: ConceptId
  readonly title: string
  readonly summary: string
  /** Concept ids that should usually precede this one. */
  readonly prerequisites: readonly ConceptId[]
  /** Course-material anchors backing the concept (may be empty for pure model knowledge). */
  readonly sourceAnchors: readonly SourceAnchor[]
  readonly difficulty?: ConceptDifficulty
  /** Known misconceptions worth diagnosing. */
  readonly misconceptions?: readonly string[]
  /** Objective checks that could verify understanding, if any. */
  readonly checkIdeas?: readonly string[]
}

/** One source document attached to a course revision, with its role. */
export interface CourseSourceRef {
  readonly sourceId: SourceId
  readonly role: SourceRole
  /** Optional note on which chapters/pages matter. */
  readonly note?: string
}

/**
 * One chapter/section grouping concepts in a course revision.
 *
 * Chapters are optional: revisions created before this field existed keep the
 * flat `concepts` + `sequence` view. When present, every concept id must also
 * exist in `concepts`, and the order of chapters is the recommended outline
 * order (concepts inside a chapter follow `sequence`).
 */
export interface CourseChapter {
  /** Stable id inside one revision. */
  readonly id: string
  readonly title: string
  /** One-line summary shown in the draft review. */
  readonly summary?: string
  readonly conceptIds: readonly ConceptId[]
  /** Source page/heading this chapter was derived from, when available. */
  readonly sourceAnchors?: readonly SourceAnchor[]
  /** Chapter role: normal chapter, appendix, or cross-chapter tool. */
  readonly role?: 'chapter' | 'appendix' | 'tool'
}

/** One immutable structure revision of a course. */
export interface CourseRevision {
  readonly id: CourseRevisionId
  readonly courseId: CourseId
  /** Monotonic per course, starting at 1. */
  readonly version: number
  readonly createdAt: string
  readonly state: RevisionState
  readonly confirmedAt?: string
  /** `ai-draft` when generated by the model, `student-edit` when edited/confirmed by the student. */
  readonly provenance: 'ai-draft' | 'student-edit' | 'source-update' | 'kb-structure' | 'llm-wiki'
  /** Student's stated goals for this course revision. */
  readonly goals: readonly string[]
  /** Optional prerequisites/background the student stated. */
  readonly background?: string
  readonly language: 'zh' | 'en' | 'bilingual'
  readonly sources: readonly CourseSourceRef[]
  readonly concepts: readonly Concept[]
  /** Recommended learning order (concept ids); must cover every concept. */
  readonly sequence: readonly ConceptId[]
  /** Optional chapter/section grouping (structure-first and llm-wiki drafts). */
  readonly chapters?: readonly CourseChapter[]
  /** Human-readable summary of what changed vs the previous revision. */
  readonly changeSummary?: string
  /** Source revisions this structure was built from (for change detection). */
  readonly basedOn: readonly { readonly sourceId: SourceId; readonly revisionId: string }[]
  /** Concepts whose material changed and that a student should review. */
  readonly needsRecheckConceptIds?: readonly ConceptId[]
}

/** Stable course identity. */
export interface Course {
  readonly id: CourseId
  readonly title: string
  readonly description: string
  readonly subjectTags: readonly string[]
  readonly status: CourseStatus
  readonly createdAt: string
  readonly updatedAt: string
  /** Confirmed revision students learn against, if any. */
  readonly activeRevisionId?: CourseRevisionId
  /** Newest proposed revision awaiting confirmation, if any. */
  readonly draftRevisionId?: CourseRevisionId
}

/** The draft structure proposed to the student for confirmation. */
export interface CourseDraftView {
  readonly course: Course
  readonly revision: CourseRevision
  /** Source coverage summary used to explain what was read. */
  readonly coverage: readonly {
    readonly sourceId: SourceId
    readonly title: string
    readonly status: string
    readonly usedUnits: number
    readonly issues: number
  }[]
  /** Warnings shown to the student before confirming. */
  readonly warnings: readonly string[]
  /** How the structure was produced. */
  readonly origin?: 'kb-structure' | 'llm-wiki' | 'ai'
  /** Human-readable notes about detection, roles and fallback coverage. */
  readonly structureNotes?: readonly string[]
}

/** Cross-course reference allowed when it genuinely helps understanding. */
export interface CrossCourseReference {
  readonly courseId: CourseId
  readonly courseTitle: string
  readonly revisionId: CourseRevisionId
  readonly conceptIds: readonly ConceptId[]
  readonly reason: string
  readonly anchors: readonly SourceAnchor[]
}
